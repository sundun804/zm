// ===== i18n helpers =====
function getNestedValue(obj, path) {
  return path.split('.').reduce((o, k) => (o || {})[k], obj)
}

export function getLanguage() {
  try {
    return localStorage.getItem('lang') || 'zh'
  } catch (e) {
    return 'zh'
  }
}

export function setLanguage(lang) {
  try {
    localStorage.setItem('lang', lang)
  } catch (e) {}
}

export function applyLanguage(lang) {
  const t = translations[lang]
  if (!t) return

  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n
    const text = getNestedValue(t, key)
    if (text !== undefined) el.textContent = text
  })

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml
    const html = getNestedValue(t, key)
    if (html !== undefined) el.innerHTML = html
  })

  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const key = el.dataset.i18nAlt
    const text = getNestedValue(t, key)
    if (text !== undefined) el.alt = text
  })

  document.title = getNestedValue(t, 'meta.title') || document.title
  const metaDesc = document.querySelector('meta[name="description"]')
  if (metaDesc) {
    metaDesc.content = getNestedValue(t, 'meta.description') || metaDesc.content
  }

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder
    const text = getNestedValue(t, key)
    if (text !== undefined) el.placeholder = text
  })
}

export function toggleLanguage() {
  const current = getLanguage()
  const next = current === 'zh' ? 'en' : 'zh'
  setLanguage(next)

  const html = document.documentElement

  // Save scroll state & find the element near the top of the viewport as anchor
  const scrollY = window.scrollY
  const anchorEl = document.elementFromPoint(window.innerWidth / 2, 120)
  const anchorRect = anchorEl ? anchorEl.getBoundingClientRect() : null

  // Inline style guarantees scroll-behavior is off regardless of CSS specificity
  html.style.scrollBehavior = 'auto'
  html.classList.add('lang-switching')

  applyLanguage(next)
  updateToggleButton(next)

  // Force reflow so new layout is committed before we measure
  void html.offsetHeight

  // Restore the anchor element to its original viewport position
  if (anchorEl && anchorRect && document.body.contains(anchorEl)) {
    const newRect = anchorEl.getBoundingClientRect()
    const delta = newRect.top - anchorRect.top
    if (delta !== 0) {
      window.scrollBy(0, delta)
    }
  } else {
    window.scrollTo(0, scrollY)
  }

  requestAnimationFrame(() => {
    // Second rAF ensures IntersectionObserver callbacks from the layout
    // change have fired while transitions are still disabled.
    requestAnimationFrame(() => {
      html.classList.remove('lang-switching')
      html.style.scrollBehavior = ''
    })
  })

  return next
}

export function updateToggleButton(lang) {
  const btn = document.getElementById('langToggle')
  if (btn) {
    const t = translations[lang]
    btn.textContent = t.nav.toggle
    btn.setAttribute('aria-label', lang === 'zh' ? 'Switch to English' : '切换到中文')
  }
}
